func OpenAPI(title string, flows []*flow.Flow) *omap {
	b := &apiBuilder{paths: map[string]*apiPath{}}
	for _, f := range flows {
		b.add(f)
	}
	doc := &omap{}
	doc.set("openapi", "3.0.3")
	doc.set("info", (&omap{}).set("title", title).set("version", "1.0.0").set("description", "Generated by ProxyGo from captured traffic."))
	var servers []any
	for _, s := range b.servers {
		servers = append(servers, (&omap{}).set("url", s))
	}
	if len(servers) > 0 {
		doc.set("servers", servers)
	}
	paths := &omap{}
	for _, p := range b.order {
		ap := b.paths[p]
		item := &omap{}
		if len(ap.params) > 0 {
			var params []any
			for _, name := range ap.params {
				params = append(params, (&omap{}).set("name", name).set("in", "path").set("required", true).set("schema", ap.paramSchema[name].build()))
			}
			item.set("parameters", params)
		}
		for _, m := range ap.methods {
			item.set(strings.ToLower(m), ap.ops[m].build(m, p))
		}
		paths.set(p, item)
	}
	doc.set("paths", paths)
	return doc
}

func WriteOpenAPI(path, title string, flows []*flow.Flow) error {
	b, err := yaml.Marshal(OpenAPI(title, flows))
	if err != nil {
		return err
	}
	return writeAtomic(path, b)
}

func WriteOpenAPIHTML(path, title string, flows []*flow.Flow) error {
	var b strings.Builder
	err := swaggerPage.Execute(&b, map[string]any{"Title": title, "Spec": OpenAPI(title, flows).jsonValue()})
	if err != nil {
		return err
	}
	return writeAtomic(path, []byte(b.String()))
}

